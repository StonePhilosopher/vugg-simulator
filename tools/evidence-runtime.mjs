function localImportSpecifiers(source) {
  const matches = [];
  const pattern = /\bfrom\s+['"](\.[^'"]+)['"]|\bimport\s*\(\s*['"](\.[^'"]+)['"]\s*\)/g;
  for (const match of source.matchAll(pattern)) matches.push(match[1] || match[2]);
  return matches;
}

function localImportClosure(entries) {
  const found = new Set();
  const pending = [...entries];
  while (pending.length) {
    const file = path.resolve(pending.pop());
    if (found.has(file)) continue;
    if (!fs.existsSync(file)) throw new Error(`evidence producer file is missing: ${file}`);
    found.add(file);
    const source = fs.readFileSync(file, 'utf8');
    for (const specifier of localImportSpecifiers(source)) {
      const imported = path.resolve(path.dirname(file), specifier);
      if (!found.has(imported)) pending.push(imported);
    }
  }
  return [...found];
}

export function producerContractFiles(root, kind) {
  const entries = PRODUCER_ENTRIES[kind];
  if (!entries) throw new Error(`unknown evidence producer kind: ${kind}`);
  const files = [
    ...localImportClosure(entries.map(relative => path.join(root, relative))),
    path.join(root, 'package-lock.json'),
  ];
  for (const file of files) {
    if (!fs.existsSync(file)) throw new Error(`evidence producer file is missing: ${path.relative(root, file)}`);
  }
  return files.sort((a, b) => a.localeCompare(b));
}

export function producerContractDigest(root, kind) {
  return hashFileSet(root, `${EVIDENCE_PRODUCER_SCHEMA}:${kind}`, producerContractFiles(root, kind));
}
