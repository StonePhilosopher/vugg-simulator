/**
 * Render the crystal flow plate as one self-contained HTML page.
 *
 * Reads data/generated/crystal-flow-tree.json (produced by
 * tools/gen-crystal-flow-tree.mjs) and injects it into
 * tools/crystal-flow-page.template.html at the FLOW_DATA marker.
 * No CDN, no build step, no external asset - the page is one file.
 *
 *   node tools/gen-crystal-flow-page.mjs [--out docs/crystal-flow-tree.html]
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const DATA = path.join(ROOT, 'data', 'generated', 'crystal-flow-tree.json');
const MARKER = '/*__FLOW_DATA__*/null';

const flag = (name, fallback) => {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : fallback;
};
const TEMPLATE = path.resolve(ROOT, flag('--template', 'tools/crystal-flow-page.template.html'));
const OUT = path.resolve(ROOT, flag('--out', 'docs/crystal-flow-tree.html'));

function gitDescribe() {
  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch { return 'unknown'; }
}

function simVersion() {
  // SIM_VERSION is the sim's own identity; read it rather than restate it.
  const source = fs.readFileSync(path.join(ROOT, 'js', '15-version.ts'), 'utf8');
  const match = source.match(/const\s+SIM_VERSION\s*=\s*(\d+)/);
  return match ? match[1] : '?';
}

/**
 * Emit the payload as pure ASCII. Mineral descriptions carry degree and
 * multiplication signs, and not every host that serves this file declares a
 * charset - an undeclared UTF-8 byte renders as mojibake.
 */
function asciiOnly(text) {
  let out = '';
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (code <= 126) { out += ch; continue; }
    for (let i = 0; i < ch.length; i++) {
      out += '\\u' + ch.charCodeAt(i).toString(16).padStart(4, '0');
    }
  }
  return out;
}

if (!fs.existsSync(DATA)) {
  console.error('[crystal-flow-page] FAIL: run tools/gen-crystal-flow-tree.mjs first');
  process.exit(1);
}

const flow = JSON.parse(fs.readFileSync(DATA, 'utf8'));
const sim = simVersion();
const commit = gitDescribe();

// Trim what the page never reads, keep what it shows.
for (const edge of flow.edges) delete edge.cites;

flow._stamp = `Vugg Simulator - SIM ${sim} - ${commit}`;
flow._provenance = 'Generated by tools/gen-crystal-flow-page.mjs from data/minerals.json and the '
  + `nucleation engines js/80-js/91 at SIM ${sim} (${commit}). `
  + 'Regenerate with: node tools/gen-crystal-flow-tree.mjs && node tools/gen-crystal-flow-page.mjs';

const template = fs.readFileSync(TEMPLATE, 'utf8');
if (!template.includes(MARKER)) {
  console.error('[crystal-flow-page] FAIL: the FLOW_DATA marker is missing from the template');
  process.exit(1);
}

// JSON.stringify never emits "</", but close that door anyway before inlining.
const payload = asciiOnly(JSON.stringify(flow).replace(/<\//g, '<\\/'));
const html = template.replace(MARKER, () => payload);

const stray = [...html].filter(ch => ch.codePointAt(0) > 126);
if (stray.length) {
  console.error(`[crystal-flow-page] FAIL: ${stray.length} non-ASCII character(s) survived into the page`);
  process.exit(1);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, html, 'ascii');
console.error(`[crystal-flow-page] wrote ${path.relative(ROOT, OUT)} `
  + `(${Math.round(html.length / 1024)} KB, ${flow.counts.minerals} species, `
  + `${flow.counts.edges} chords, SIM ${sim})`);
